import { localPhotoPath } from './photoSources'
import type { QuizOption, QuizQuestion, SeasonScores } from '../types'

const s = (
  spring: number,
  summer: number,
  autumn: number,
  winter: number,
): SeasonScores => ({ spring, summer, autumn, winter })

function opt(
  id: string,
  label: string,
  scores: SeasonScores,
  placeholderColor: string,
): QuizOption {
  return {
    id,
    label,
    scores,
    photo: localPhotoPath(id),
    placeholderColor,
  }
}

