export function seasonThemeStyle(
  seasonId: SeasonId,
): Record<string, string> {
  const t = seasons[seasonId].theme
  return {
    '--bg': t.bg,
    '--surface': t.surface,
    '--border': t.border,
    '--accent': t.accent,
    '--accent-bg': t.accentBg,
    '--accent-border': t.accentBorder,
    '--text': t.text,
    '--text-h': t.textH,
    '--text-muted': t.textMuted,
    '--season-accent': seasons[seasonId].accent,
  }
}
